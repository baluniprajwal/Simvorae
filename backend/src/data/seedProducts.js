function slugify(value) {
  return value
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
}

function createImages(url, name) {
  return [
    {
      url,
      alt: name,
      isPrimary: true,
      order: 0,
    },
  ];
}

